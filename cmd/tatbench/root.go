package main

import (
	"fmt"
	"os"

	"github.com/spf13/cobra"
)

const version = "1.0.0"

var rootCmd = &cobra.Command{
	Use:           "tatbench",
	Short:         "Benchmark and stress-test TatCoin nodes",
	SilenceUsage:  true,
	SilenceErrors: true,
}

func Execute() {
	if err := rootCmd.Execute(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func init() {
	rootCmd.AddCommand(
		newRPCCommand(),
		newTXCommand(),
		newAccountsCommand(),
		newVersionCommand(),
	)
}
